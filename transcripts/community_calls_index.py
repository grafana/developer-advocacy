"""Generate transcripts/community-calls.md, an index of all community calls.

The index is built from the transcript files in this directory, so re-run it
after fetching new transcripts with transcripts.py:

    python3 community_calls_index.py

Only the standard library is needed.
"""
import html
import os
import re
import argparse

HERE = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.join(HERE, "community-calls.md")

# Order matters: the first match wins. Each entry is (show name, regex on the title,
# link to the per-show page under projects/ or None).
SHOWS = [
    ("Grafana OpenTelemetry Community Call", r"opentelemetry community call|alloy, opentelemetry|otel and alloy|opamp", "../projects/Grafana OTel Community Call/README.md"),
    ("Loki Community Call", r"loki", "../projects/Loki Community Calls/Loki Community Calls.md"),
    ("Tempo Community Call", r"tempo", None),
    ("Mimir Community Call", r"mimir", None),
    ("Alloy and Grafana Agent Community Call", r"alloy|grafana agent", None),
    ("Beyla Community Call", r"beyla", None),
    ("Pyroscope Community Call", r"pyroscope", None),
    ("OnCall Community Call", r"oncall", None),
    ("Grafana Campfire (Grafana Community Call)", r"campfire", None),
]
OTHER = "Other Community Calls"


def read_transcript(path):
    """Return the metadata and one-line topic for a transcript file."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    lines = text.split("\n")
    title = html.unescape(lines[0].lstrip("# ").strip())
    published = re.search(r"^Published on (\S+)", text, re.M)
    url = re.search(r"^URL: (\S+)", text, re.M)
    summary = re.search(r"^## Summary\s*\n+(.+?)\n\s*\n", text, re.M | re.S)
    return {
        "title": title,
        "date": published.group(1)[:10] if published else os.path.basename(path)[:10],
        "url": url.group(1) if url else "",
        "topic": one_line(summary.group(1)) if summary else "",
        "file": os.path.basename(path),
    }


def one_line(summary, limit=220):
    """First sentence of the summary, shortened to a single line."""
    summary = html.unescape(" ".join(summary.split()))
    sentence = re.split(r"(?<=[.!?])\s", summary, maxsplit=1)[0]
    if len(sentence) > limit:
        sentence = sentence[:limit].rsplit(" ", 1)[0].rstrip(",;:") + "..."
    return sentence


def show_for(title):
    for name, pattern, _ in SHOWS:
        if re.search(pattern, title, re.I):
            return name
    return OTHER


def collect():
    """Find community calls: transcripts whose title contains 'community call'."""
    calls = []
    for name in sorted(os.listdir(HERE)):
        if not name.endswith(".md") or name in ("README.md", "community-calls.md"):
            continue
        info = read_transcript(os.path.join(HERE, name))
        if re.search(r"community call", info["title"], re.I):
            info["show"] = show_for(info["title"])
            calls.append(info)
    return calls


def render(calls):
    out = [
        "# Grafana Community Calls",
        "",
        "Index of past Grafana community calls, grouped by show and listed newest first. "
        "Each entry has the YouTube publish date, the title, a one-line topic and the video link. "
        "Full transcripts are in this directory.",
        "",
        f"This file is generated by `community_calls_index.py` from the transcripts: {len(calls)} calls. "
        "Do not edit it by hand.",
        "",
        "## Shows",
        "",
    ]
    order = [name for name, _, _ in SHOWS] + [OTHER]
    pages = {name: page for name, _, page in SHOWS}
    by_show = {name: [c for c in calls if c["show"] == name] for name in order}
    for name in order:
        if by_show[name]:
            out.append(f"- [{name}](#{anchor(name)}) ({len(by_show[name])})")
    out += ["", "More notes per show: "
            "[OpenTelemetry community call notes](../projects/Grafana%20OTel%20Community%20Call/README.md), "
            "[Loki community call notes](../projects/Loki%20Community%20Calls/Loki%20Community%20Calls.md).", ""]
    for name in order:
        group = sorted(by_show[name], key=lambda c: c["date"], reverse=True)
        if not group:
            continue
        out += [f"## {name}", ""]
        if pages.get(name):
            out += [f"Per-show page: [{pages[name].split('/')[-2]}]({pages[name].replace(' ', '%20')})", ""]
        for c in group:
            line = f"- {c['date']} - [{c['title']}]({c['url']})"
            if c["topic"]:
                line += f": {c['topic']}"
            out.append(line)
        out.append("")
    return "\n".join(out)


def anchor(heading):
    slug = re.sub(r"[^\w\s-]", "", heading.lower())
    return re.sub(r"\s", "-", slug.strip())


def main():
    parser = argparse.ArgumentParser(description="Generate the community calls index from transcript files.")
    parser.add_argument("-o", "--output", default=OUTPUT, help="Output file (default: community-calls.md)")
    args = parser.parse_args()
    calls = collect()
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(render(calls) + "\n")
    print(f"Wrote {len(calls)} community calls to {args.output}")


if __name__ == "__main__":
    main()
